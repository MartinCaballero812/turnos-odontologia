CREATE TABLE IF NOT EXISTS sede (
    id bigint PRIMARY KEY,
    nombre text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS recepcion (
    id bigint PRIMARY KEY,
    sede_id bigint NOT NULL REFERENCES sede,
    nombre text NOT NULL
);

CREATE TABLE IF NOT EXISTS odontologo (
    id bigint PRIMARY KEY,
    sede_id bigint NOT NULL REFERENCES sede,
    nombre text NOT NULL,
    UNIQUE (id, sede_id)
);

CREATE TABLE IF NOT EXISTS sillon (
    id bigint PRIMARY KEY,
    sede_id bigint NOT NULL REFERENCES sede,
    nombre text NOT NULL,
    UNIQUE (id, sede_id),
    UNIQUE (sede_id, nombre)
);

CREATE TABLE IF NOT EXISTS franja_atencion (
    sede_id bigint NOT NULL REFERENCES sede,
    dia_semana smallint NOT NULL CHECK (dia_semana BETWEEN 1 AND 5),
    codigo text NOT NULL CHECK (codigo IN ('MANANA', 'TARDE')),
    inicio time NOT NULL,
    fin time NOT NULL,
    CHECK (inicio < fin),
    PRIMARY KEY (sede_id, dia_semana, codigo)
);

CREATE TABLE IF NOT EXISTS asignacion_franja (
    odontologo_id bigint NOT NULL,
    sede_id bigint NOT NULL,
    dia_semana smallint NOT NULL,
    franja_codigo text NOT NULL,
    PRIMARY KEY (odontologo_id, dia_semana),
    FOREIGN KEY (odontologo_id, sede_id) REFERENCES odontologo (id, sede_id),
    FOREIGN KEY (sede_id, dia_semana, franja_codigo) REFERENCES franja_atencion
);

CREATE TABLE IF NOT EXISTS cierre_sede (
    sede_id bigint NOT NULL REFERENCES sede,
    fecha date NOT NULL,
    PRIMARY KEY (sede_id, fecha)
);

CREATE TABLE IF NOT EXISTS paciente (
    id bigint PRIMARY KEY,
    nombre text NOT NULL
);

CREATE TABLE IF NOT EXISTS prestacion (
    id bigint PRIMARY KEY,
    nombre text NOT NULL,
    duracion_minutos integer NOT NULL CHECK (duracion_minutos > 0),
    usa_sillon boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS turno (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sede_id bigint NOT NULL REFERENCES sede,
    paciente_id bigint NOT NULL REFERENCES paciente,
    odontologo_id bigint NOT NULL,
    sillon_id bigint,
    prestacion_id bigint NOT NULL REFERENCES prestacion,
    inicio timestamp NOT NULL,
    fin timestamp NOT NULL,
    fin_pausa timestamp NOT NULL,
    duracion_minutos integer NOT NULL CHECK (duracion_minutos > 0),
    CHECK (fin = inicio + duracion_minutos * interval '1 minute'),
    CHECK (fin_pausa = fin + interval '10 minutes'),
    FOREIGN KEY (odontologo_id, sede_id) REFERENCES odontologo (id, sede_id),
    FOREIGN KEY (sillon_id, sede_id) REFERENCES sillon (id, sede_id)
);

CREATE INDEX IF NOT EXISTS turno_odontologo_inicio ON turno (odontologo_id, inicio);
CREATE INDEX IF NOT EXISTS turno_sillon_inicio ON turno (sillon_id, inicio) WHERE sillon_id IS NOT NULL;
